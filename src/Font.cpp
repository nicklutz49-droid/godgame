float addText(MeshData& md, const char* text, float x, float y, float scale,
              const glm::vec3& color) {
  const glm::vec3 n(0.0f, 0.0f, 1.0f);
  float pen = x;
  for (const char* p = text; *p; ++p) {
    if (*p == ' ') {
      pen += kAdvance * scale;
      continue;
    }
    const std::uint8_t* rows = glyphRows(*p);
    if (!rows) {
      pen += kAdvance * scale;
      continue;
    }
    for (int r = 0; r < 7; ++r) {
      for (int cbit = 0; cbit < 5; ++cbit) {
        if (!(rows[r] & (1 << (4 - cbit)))) continue;
        float px = pen + static_cast<float>(cbit) * scale;
        float py = y + static_cast<float>(r) * scale;
        std::uint32_t base = md.vertexCount();
        md.addVertex(glm::vec3(px, py, 0.0f), n, color);
        md.addVertex(glm::vec3(px + scale, py, 0.0f), n, color);
        md.addVertex(glm::vec3(px + scale, py + scale, 0.0f), n, color);
        md.addVertex(glm::vec3(px, py + scale, 0.0f), n, color);
        md.addTriangle(base, base + 1, base + 2);
        md.addTriangle(base, base + 2, base + 3);
      }
    }
    pen += kAdvance * scale;
  }
  return pen;
}

float textWidth(const char* text, float scale) {
  float w = 0.0f;
  for (const char* p = text; *p; ++p) w += kAdvance * scale;
  return w > 0.0f ? w - 1.0f * scale : 0.0f;  // trailing air trimmed
}

